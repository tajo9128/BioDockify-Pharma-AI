def generate_ai_disclosure(venue: str, tool_name: str, tasks: List[str],
                           author_role: str = "reviewed and edited") -> Dict[str, Any]:
    """Generate an AI usage disclosure statement for a specific venue.

    Args:
        venue: Venue key (icmje, nature, science, ieee, acl, fda_ema)
        tool_name: Name of the AI tool used (e.g., "BioDockify AI Engine")
        tasks: List of tasks AI was used for
        author_role: What the authors did (default: reviewed and edited)

    Returns:
        {statement, venue_policy, placement, notes}
    """
    venue = venue.lower().strip()
    policy = VENUE_AI_POLICIES.get(venue, VENUE_AI_POLICIES["icmje"])

    tasks_str = "; ".join(tasks) if tasks else "language editing and formatting"

    statement = policy["template"].replace("[AI TOOL NAME]", tool_name)
    statement = statement.replace("[TOOL NAME]", tool_name)
    statement = statement.replace("[DESCRIPTION]", "pharmaceutical research AI assistant")
    statement = statement.replace("[REASON FOR USE]", tasks_str)
    statement = statement.replace("[SPECIFIC TASK]", tasks_str)
    statement = statement.replace("[AUTHOR(S)]", "The authors")
    statement = statement.replace("[AUTHOR(S)]", "The authors")

    # Add author responsibility clause
    statement += f"\n\nThe author(s) {author_role} all AI-assisted content and take(s) full responsibility for the content of this publication."

    return {
        "venue": policy["name"],
        "statement": statement,
        "placement": policy["placement"],
        "prohibitions": policy["prohibits"],
        "requires_disclosure": policy["requires_disclosure"],
        "url": policy["url"],
    }


