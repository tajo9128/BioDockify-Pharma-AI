def build_prisma_flow_diagram(identified: int, screened: int, excluded_title: int,
                              full_text_assessed: int, excluded_full_text: int,
                              included: int, reasons_excluded: List[str] = None) -> Dict[str, Any]:
    """Generate PRISMA 2020 flow diagram data.

    Args:
        identified: Records identified through database searching
        screened: Records screened by title/abstract
        excluded_title: Records excluded at title/abstract stage
        full_text_assessed: Full-text articles assessed for eligibility
        excluded_full_text: Full-text articles excluded
        included: Studies included in synthesis
        reasons_excluded: List of exclusion reasons (for the diagram)

    Returns:
        Flow diagram data for rendering.
    """
    return {
        "identification": {
            "records_identified": identified,
            "duplicates_removed": identified - screened,
        },
        "screening": {
            "records_screened": screened,
            "records_excluded": excluded_title,
            "full_text_retrieved": full_text_assessed,
        },
        "eligibility": {
            "full_text_assessed": full_text_assessed,
            "full_text_excluded": excluded_full_text,
            "exclusion_reasons": reasons_excluded or ["Did not meet inclusion criteria"],
        },
        "included": {
            "studies_included": included,
            "studies_in_synthesis": included,
        },
        "mermaid": (
            f"graph TD\n"
            f"  A[Records identified: {identified}] --> B[After duplicates: {screened}]\n"
            f"  B --> C[Screened: {screened}]\n"
            f"  C --> D[Excluded: {excluded_title}]\n"
            f"  C --> E[Full-text assessed: {full_text_assessed}]\n"
            f"  E --> F[Excluded: {excluded_full_text}]\n"
            f"  E --> G[Included: {included}]\n"
        ),
    }


