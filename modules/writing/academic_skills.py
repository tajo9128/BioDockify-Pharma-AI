def build_review_prompt(manuscript_text: str, reviewer_role: str) -> str:
    """Build a peer review prompt for a specific reviewer role.

    Args:
        manuscript_text: The manuscript to review (or summary)
        reviewer_role: One of the roles in PEER_REVIEW_PANEL

    Returns:
        A prompt string for the LLM to generate a review.
    """
    reviewer = None
    for r in PEER_REVIEW_PANEL["reviewers"]:
        if r["role"].lower().replace(" ", "_") == reviewer_role.lower().replace(" ", "_"):
            reviewer = r
            break

    if not reviewer:
        return ""

    focus = "\n".join(f"  - {f}" for f in reviewer["focus_areas"])
    dims = ", ".join(reviewer["scoring_dimensions"])

    return (
        f"You are a {reviewer['role']} — {reviewer['persona']}.\n\n"
        f"Review the following manuscript and provide:\n"
        f"1. A summary (2-3 sentences) of the manuscript's main contribution\n"
        f"2. Specific strengths (2-4 points)\n"
        f"3. Specific weaknesses/concerns (2-4 points)\n"
        f"4. Scoring on: {dims} (1-10 scale each)\n"
        f"5. Overall recommendation: Accept / Minor Revision / Major Revision / Reject\n"
        f"6. Three specific questions for the authors to address\n\n"
        f"Focus especially on:\n{focus}\n\n"
        f"Be rigorous and specific. Cite sections/paragraphs. Do not be sycophantic.\n\n"
        f"MANUSCRIPT:\n{manuscript_text[:8000]}\n"
    )


