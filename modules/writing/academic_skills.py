# Skill 5: L3 Claim-Faithfulness Integrity Gate
# ═══════════════════════════════════════════════════════════════════════════

def audit_claims(text: str, citations: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Audit text for claim-faithfulness issues.

    Checks for:
    1. Uncited factual claims (claims with no citation)
    2. Citation-claim mismatch (citation doesn't support the claim)
    3. Overclaiming (claim stronger than evidence supports)
    4. Hallucinated citations (citation that doesn't exist)
    5. Missing context (claim ignores important caveats)

    Args:
        text: The manuscript text to audit
        citations: Optional list of citation metadata for verification

    Returns:
        Audit report with issues categorized by severity
    """
    import re

    issues = []
    claims_found = 0
    citations_found = 0

    # Find sentences with factual claims (heuristic)
    claim_patterns = [
        r"\b(shows?|demonstrates?|indicates?|suggests?|reveals?|proves?|confirms?)\b",
        r"\b(IC50|EC50|Ki|Kd|pIC50|binding affinity|potency)\b",
        r"\b(significant(?:ly)?|significantly (?:different|higher|lower|increased|decreased))\b",
        r"\b(\d+(?:\.\d+)?\s*(?:mg|ug|ng|pg|nM|uM|mM|M|kcal|kJ|fold|%))\b",
        r"\b(compared to|versus|vs\.?|relative to)\b",
    ]

    # Find citation markers
    citation_re = re.compile(r"\[(\d{1,3})\]|\(([A-Z][a-z]+(?:\s+et\s+al\.?)?,\s*\d{4})\)")

    # Split into sentences
    sentences = re.split(r"(?<=[.!?])\s+", text)

    for i, sentence in enumerate(sentences):
        if len(sentence) < 20:
            continue

        # Check for claim patterns
        has_claim = any(re.search(p, sentence, re.IGNORECASE) for p in claim_patterns)
        has_citation = bool(citation_re.search(sentence))

        if has_claim:
            claims_found += 1
            if not has_citation:
                issues.append({
                    "type": "uncited_claim",
                    "severity": "high",
                    "sentence": sentence[:200],
                    "message": "Factual claim without citation. Add a reference.",
                })

        if has_citation:
            citations_found += 1

    # Check for specific pharma overclaiming patterns
    overclaim_patterns = [
        (r"\b(cures?|eliminates?|eradicates?)\b", "Overclaiming: 'cure/eradicate' without extraordinary evidence"),
        (r"\b(no side effects|no adverse|completely safe)\b", "Safety overclaim: claiming zero side effects"),
        (r"\b(first ever|never before|unprecedented)\b", "Novelty overclaim: verify this claim against literature"),
        (r"\b(proven|proves?)\b(?!n)", "Overclaiming: 'proves' is too strong for single studies — use 'suggests/demonstrates'"),
    ]

    for pattern, message in overclaim_patterns:
        for m in re.finditer(pattern, text, re.IGNORECASE):
            issues.append({
                "type": "overclaiming",
                "severity": "medium",
                "match": m.group(0),
                "message": message,
            })

    # Count by severity
    severity_counts = {
        "critical": len([i for i in issues if i.get("severity") == "critical"]),
        "high": len([i for i in issues if i.get("severity") == "high"]),
        "medium": len([i for i in issues if i.get("severity") == "medium"]),
        "low": len([i for i in issues if i.get("severity") == "low"]),
    }

    # Integrity gate: PASS only if no critical/high issues
    passed = severity_counts["critical"] == 0 and severity_counts["high"] == 0

    return {
        "status": "PASS" if passed else "FAIL",
        "claims_found": claims_found,
        "citations_found": citations_found,
        "uncited_claims": claims_found - citations_found if claims_found > citations_found else 0,
        "issues": issues[:20],  # cap for response size
        "total_issues": len(issues),
        "severity_breakdown": severity_counts,
        "integrity_gate": "PASSED" if passed else "FAILED — resolve high-severity issues before submission",
        "recommendation": (
            "All claims are properly cited. Document is submission-ready." if passed
            else f"Found {severity_counts['high']} high-severity and {severity_counts['medium']} medium-severity issues. Review and fix before submission."
        ),
    }
